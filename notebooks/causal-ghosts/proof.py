# =====================================================================
# CELL 2: Rung 1 vs Rung 2 Recap (Confounding & do-operator)
# =====================================================================
n_recap = 5000
w_recap = np.random.beta(2, 5, size=n_recap) 
x_recap = np.random.binomial(1, p=np.clip(0.8 - w_recap, 0.0, 1.0))
y_recap = 2.0 * x_recap + 35.0 * w_recap + np.random.normal(0, 0.1, size=n_recap)

naive_coef = y_recap[x_recap == 1].mean() - y_recap[x_recap == 0].mean()
reg_recap = LinearRegression().fit(np.column_stack((x_recap, w_recap)), y_recap)
adjusted_coef = reg_recap.coef_[0]

print(f"\n--- RUNG 1 vs RUNG 2 RECAP ---")
print(f"Naive Observational Coefficient P(Y | X) : {naive_coef:.4f}")
print(f"True Causally Adjusted Effect P(Y | do(X)): {adjusted_coef:.4f} (True: 2.0000)")

# =====================================================================
# CELL 3: Twin-Network Counterfactual Estimator
# =====================================================================
n_twin = 1000
x_twin = np.random.normal(0, 1, n_twin)
u_t = np.random.normal(0, 1, n_twin)
u_y = np.random.normal(0, 0.5, n_twin)

t_twin = 0.5 * x_twin + u_t
y_twin = 2.0 * t_twin + 1.5 * x_twin + u_y

X_reg = np.column_stack((t_twin, x_twin))
scm_model = LinearRegression().fit(X_reg, y_twin)
beta_t = scm_model.coef_[0]
beta_x = scm_model.coef_[1]
alpha_intercept = scm_model.intercept_

x_obs_0 = x_twin[0]
t_obs_0 = t_twin[0]
y_obs_0 = y_twin[0]

u_y_abducted = y_obs_0 - (beta_t * t_obs_0 + beta_x * x_obs_0 + alpha_intercept)
t_counterfactual = 1.0 - t_obs_0
y_counterfactual_pred = beta_t * t_counterfactual + beta_x * x_obs_0 + alpha_intercept + u_y_abducted
y_counterfactual_true = 2.0 * t_counterfactual + 1.5 * x_obs_0 + u_y[0]

print(f"\n--- TWIN-NETWORK INDIVIDUAL RETROSPECTIVE ---")
print(f"Factual Observation of Subject 0: X={x_obs_0:.4f}, T={t_obs_0:.4f}, Y={y_obs_0:.4f}")
print(f"Abducted Noise Variable U_Y       : {u_y_abducted:.4f} (True U_Y: {u_y[0]:.4f})")
print(f"Counterfactual Action            : Force T from {t_obs_0:.4f} to {t_counterfactual:.4f}")
print(f"Predicted Counterfactual Outcome : {y_counterfactual_pred:.4f}")
print(f"True Counterfactual Outcome      : {y_counterfactual_true:.4f}")
print(f"Absolute Prediction Error        : {abs(y_counterfactual_true - y_counterfactual_pred):.6f}")

# =====================================================================
# CELL 4: Empirical Surprise 1: ITE Heterogeneity Under Zero ATE
# =====================================================================
np.random.seed(42)
n_surprise = 5000

z_s = np.random.normal(0, 1, n_surprise)           
u_y_s = np.random.normal(0, 0.5, n_surprise)      
p_select = 1 / (1 + np.exp(-0.5 * z_s))
t_s = np.random.binomial(1, p_select)

y0_s = 3.0 * z_s + u_y_s                     
y1_s = 3.0 * z_s + 2.0 * z_s + u_y_s          
y_obs_s = t_s * y1_s + (1 - t_s) * y0_s

ate_observational = y_obs_s[t_s == 1].mean() - y_obs_s[t_s == 0].mean()
true_ate_interventional = (y1_s - y0_s).mean()            
individual_effects = y1_s - y0_s                     

percent_harmed = (individual_effects < 0).mean() * 100
percent_saved = (individual_effects > 0).mean() * 100

print(f"\n--- EMPIRICAL SURPRISE 1: HETEROGENEITY ---")
print(f"Rung 1 Observational Difference P(Y|T=1)-P(Y|T=0)  : {ate_observational:.4f}")
print(f"Rung 2 Population Causal Effect (True ATE)        : {true_ate_interventional:.4f}")
print(f"Rung 3 Individual Treatment Effect (ITE) Deviation: {individual_effects.std():.4f}")
print(f"True ITE Minimum Value                            : {individual_effects.min():.4f}")
print(f"True ITE Maximum Value                            : {individual_effects.max():.4f}")
print(f"Percentage of Population Actively Harmed by Policy : {percent_harmed:.2f}%")
print(f"Percentage of Population Actively Saved by Policy  : {percent_saved:.2f}%")

# =====================================================================
# CELL 5: Empirical Surprise 2: Non-Identifiability and Manski Bounds
# =====================================================================
np.random.seed(42)
n_bounds = 10000

u_b = np.random.uniform(0, 1, n_bounds)
v_b = np.random.uniform(0, 1, n_bounds)  # Structural noise for Y
t_b = (np.random.uniform(0, 1, n_bounds) < 0.3 + 0.4 * u_b).astype(int)
y_b = (v_b < 0.5 * t_b + 0.4 * u_b).astype(int)

# Calculating Manski's worst-case non-parametric bounds for the ATE
p_y1_t1 = y_b[t_b==1].mean()
p_y1_t0 = y_b[t_b==0].mean()
p_t1 = t_b.mean()
p_t0 = 1.0 - p_t1

manski_lb = p_y1_t1 * p_t1 + 0.0 * p_t0 - (p_y1_t0 * p_t0 + 1.0 * p_t1)
manski_ub = p_y1_t1 * p_t1 + 1.0 * p_t0 - (p_y1_t0 * p_t0 + 0.0 * p_t1)
manski_width = manski_ub - manski_lb

monotonicity_lb = 0.0
monotonicity_ub = p_y1_t1 * p_t1 + (1.0 - p_y1_t0) * p_t0
mon_width = monotonicity_ub - monotonicity_lb
improvement = (1 - (mon_width / manski_width)) * 100

# Calculate true causal effect from potential outcomes on the same subjects
y1_b = (v_b < 0.5 * 1 + 0.4 * u_b).astype(int)
y0_b = (v_b < 0.5 * 0 + 0.4 * u_b).astype(int)
true_effect = (y1_b - y0_b).mean()

print(f"\n--- EMPIRICAL SURPRISE 2: NON-IDENTIFIABILITY ---")
print(f"Without assumptions, ATE in [{manski_lb:.4f}, {manski_ub:.4f}] — width = {manski_width:.4f}")
print(f"With monotonicity, ATE in [{monotonicity_lb:.4f}, {monotonicity_ub:.4f}] — width = {mon_width:.4f}")
print(f"True Simulated Causal Effect: {true_effect:.4f} (Theoretical: 0.5000)")
print(f"The monotonicity assumption reduced uncertainty by {improvement:.2f}%")

