ax1.set_title('Individual Treatment Effects (ITE) Distribution', fontsize=13, fontstyle='italic', pad=15, color='#c8bfaa')
ax1.set_xlabel('Population Index (Sorted by Effect Size)', fontsize=11, color='#c8bfaa')
ax1.set_ylabel('Causal Treatment Effect ($Y_1 - Y_0$)', fontsize=11, color='#c8bfaa')
ax1.grid(True, color='#1f1e1b', alpha=0.5)
