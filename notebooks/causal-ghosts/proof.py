# Plot 2: Causal Effect Bounds Comparison
ax2.set_facecolor('#141310')
bounds_labels = ['Manski Worst-Case\n(No Assumptions)', 'Monotonicity\n(Assumed No-Harm)']
lower_limits = [manski_lb, monotonicity_lb]
upper_limits = [manski_ub, monotonicity_ub]

# Draw bounds as horizontal bars
ax2.barh(bounds_labels, [upper_limits[0] - lower_limits[0], upper_limits[1] - lower_limits[1]], 
         left=lower_limits, height=0.3, color=['#8b7355', '#4a3f2f'], edgecolor='#2a2823', alpha=0.8)

# Mark the factual true causal effect
ax2.axvline(true_effect, color='#c8bfaa', linestyle='--', linewidth=2, label=f'True Causal Effect ({true_effect:.4f})')
