ax2.set_title('Epistemic Constraints on Causal Reasoning', fontsize=13, fontstyle='italic', pad=15, color='#c8bfaa')
ax2.set_xlabel('Causal Effect Size (ATE)', fontsize=11, color='#c8bfaa')
ax2.set_xlim([-0.5, 1.0])
ax2.grid(True, color='#1f1e1b', alpha=0.5)
ax2.legend(loc='lower right', frameon=False, labelcolor='#c8bfaa')

